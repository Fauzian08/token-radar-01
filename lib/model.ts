// Token Radar, model radar-2: one sealed snapshot in, one ranked board out.
//
// The board ranks every protocol the snapshot records as pre-token and not a wrapped,
// staked or bridged product of a token that already trades. The watchlist is the floor:
// all 40 of its slugs are on the board, and the board adds every other protocol that
// passes the same exclusion rule, below the floor or above it. Nothing is ranked by name:
// one function scores every row from the snapshot's own figures.
//
// Implied value, per protocol:
//
//   multiple   = the category's live-market multiple: the median market-cap/TVL of the
//                live-token protocols in the same category, shrunk toward the global
//                median (five pseudo-protocols) and clamped to [0.05, 1.00]. Each live
//                ratio is winsorized to [0.02, 2.00] first, so one small protocol whose
//                token trades far above its TVL cannot set a category's price. A category
//                with no live protocols takes the global median. The multiple is read
//                off the snapshot's own live market, never set by hand per name.
//   growth     = clamp(change_7d, -60, 120) per cent
//   growthMult = 1 + (growth / 100) x 0.5
//   maturity   = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age unknown: 365 days)
//   breadth    = 1 + 0.02 x min(chains - 1, 10)
//   implied    = max(1, round(tvl_usd x multiple x growthMult x maturity x breadth))
//
// Launch likelihood is a second, separate signal, 0-100, from four components:
//
//   size     = log10(tvl_usd / 5,000,000) / log10(1,000,000,000 / 5,000,000), clamped
//   growth   = (clamp(change_7d, -30, 60) + 30) / 90
//   maturity = min(age_days, 1095) / 1095
//   breadth  = min(chains, 10) / 10
//   score    = round(100 x (0.35 x size + 0.25 x growth + 0.25 x maturity + 0.15 x breadth))
//
// The board is ranked by implied value, as the gate requires. Likelihood is shown beside
// it and the dashboard can sort by it; it never reorders the board's ranks.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

